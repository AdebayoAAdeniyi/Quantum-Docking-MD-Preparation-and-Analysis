#!/usr/bin/env bash
# =============================================================================
#  rosetta-relax.sh - stage 4 of RosettaCM: relax the models and rank them
#
#  Dual-space FastRelax over every hybridize model, then a score table so the
#  best can be picked. Disulfide connectivity and, for a membrane protein, the
#  span file are passed through, because relax will otherwise happily pull a
#  disulfide apart or push a transmembrane helix into the solvent.
#
#  usage: rosetta-relax.sh -t TARGET -s DIR [options]
#    -t TARGET     target name (e.g. e2)
#    -s DIR        directory of models to relax (hybridize output_structures/)
#    -o DIR        output directory (default: 4_relax)
#    -n N          relaxed structures per input model (default: 5)
#    -d FILE       disulfide pairs, one "RES1 RES2" per line
#    -M            membrane protein: use the membrane weights and span file
#    -S DIR        stage 1 directory, for the span file (default: 1_setup)
#    -w NAME       score weights (default: ref2015, or the membrane set with -M)
#    -m N          only relax the N best-scoring input models
#    -q            write the job script and stop, for the queue
#    -h            this help
#
#  On -d: Rosetta assigns disulfides from geometry unless told otherwise, so a
#  model where two cysteines drifted apart loses the bond and relaxes into a
#  different fold. Give the pairs in pose numbering, which for a model built
#  from one chain numbered from 1 is the residue number.
#
#  On -w: the original script used stage3_rlx_membrane.wts for hybridize and
#  then membrane_highres_Menv_smooth.wts here, which are different score
#  functions, so the ranking from stage 3 and the ranking from stage 4 were not
#  comparable. The weights are an explicit argument now and the default is
#  stated in the output.
# =============================================================================
set -euo pipefail
source "$(dirname "$0")/../../lib/common.sh"
source "$QDM_ROOT/config/cluster.conf"
[[ -f "$QDM_ROOT/config/cluster.local.conf" ]] && source "$QDM_ROOT/config/cluster.local.conf"

target=""; src=""; out="4_relax"; nstruct=5; disulf=""; membrane=0
setup="1_setup"; weights=""; maxmodels=0; queue=0
while getopts "t:s:o:n:d:MS:w:m:qh" o; do case $o in
    t) target=$OPTARG ;; s) src=$OPTARG ;; o) out=$OPTARG ;; n) nstruct=$OPTARG ;;
    d) disulf=$OPTARG ;; M) membrane=1 ;; S) setup=$OPTARG ;; w) weights=$OPTARG ;;
    m) maxmodels=$OPTARG ;; q) queue=1 ;;
    h) sed -n '2,/^# ====/p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option; -h for usage" ;;
esac; done

[[ -n "$target" ]] || die "a target name is required (-t); -h for usage"
[[ -n "$src"    ]] || die "a model directory is required (-s); -h for usage"
[[ -d "$src"    ]] || die "model directory not found: $src"
mkdir -p "$out"

shopt -s nullglob
models=("$src"/*.pdb)
(( ${#models[@]} )) || die "no PDB models in $src"

if ((maxmodels > 0)) && (( ${#models[@]} > maxmodels )); then
    warn "-m $maxmodels given but input models carry no scores yet; taking the first $maxmodels by name"
    warn "to rank first, run extract/rosetta-scores.sh on the hybridize output"
    models=("${models[@]:0:maxmodels}")
fi

if ((membrane)); then
    cp "$setup/$target.span" "$out/" 2>/dev/null || die "-M needs $setup/$target.span"
    weights="${weights:-membrane_highres_Menv_smooth.wts}"
else
    weights="${weights:-ref2015}"
fi

if [[ -n "$disulf" ]]; then
    [[ -f "$disulf" ]] || die "disulfide file not found: $disulf"
    # Two integers per line. A malformed line here is silently ignored by
    # Rosetta, which then builds the model without that bond.
    awk 'NF && $0 !~ /^#/ { if (NF != 2 || $1 !~ /^[0-9]+$/ || $2 !~ /^[0-9]+$/)
         { printf "line %d of the disulfide file is not two residue numbers: %s\n", NR, $0 > "/dev/stderr"; bad=1 } }
         END { exit bad }' "$disulf" || die "fix the disulfide file and run again"
    grep -v '^#' "$disulf" | grep . > "$out/$target.disulfide"
    info "$(grep -c . "$out/$target.disulfide") disulfide pair(s) will be enforced"
fi

{
    cat <<EOF
# FastRelax in dual space, generated by rosetta-relax.sh
-nstruct $nstruct
-score:weights $weights

# dual space relax: internal coordinates and Cartesian together
-relax:dualspace
-relax:minimize_bond_angles
-default_max_cycles 200

# score proline ring closure through its bond terms rather than the virtual
# atom, which is required when cart_bonded is switched on
-set_weights cart_bonded 0.5 pro_close 0

-out:file:fullatom
-out:pdb
-out:path:all .
-overwrite
EOF
    [[ -n "$disulf" ]] && printf -- '-in:fix_disulf %s.disulfide\n' "$target"
    ((membrane)) && cat <<EOF

# membrane scoring
-in:file:spanfile $target.span
-membrane:no_interpolate_Mpair
-membrane:Menv_penalties
EOF
} > "$out/relax.options"

info "wrote $out/relax.options (weights: $weights)"
info "${#models[@]} input model(s), $nstruct relaxed structure(s) each"

require_rosetta relax      # needed to run; the options file above is written already
exe=$(rosetta_exe relax)
mpi_exe=$(rosetta_exe relax mpi 2>/dev/null || true)

{
    printf '#!/usr/bin/env bash\nset -euo pipefail\n%s\ncd "$(dirname "$0")"\n\n' "${ROSETTA_SETUP:-}"
    printf 'failed=0\n'
    for m in "${models[@]}"; do
        base=$(strip_ext "$m")
        abs=$(cd "$(dirname "$m")" && pwd)/$(basename "$m")
        if [[ -n "$mpi_exe" && "${CORES:-1}" -gt 1 ]]; then
            printf 'mpirun -np %s %s @relax.options -s %q -out:prefix %q || failed=$((failed+1))\n' \
                   "${CORES}" "$mpi_exe" "$abs" "${base}_relax_"
        else
            printf '%s @relax.options -s %q -out:prefix %q || failed=$((failed+1))\n' \
                   "$exe" "$abs" "${base}_relax_"
        fi
    done
    cat <<'EOF'

if ((failed)); then
    echo "$failed relax job(s) failed; the score table below covers only the rest" >&2
fi
shopt -s nullglob
sc=(*.fasc *.sc)
if ((${#sc[@]} == 0)); then
    echo "no score files were written; relax produced nothing" >&2
    exit 1
fi
echo
echo "Ranking the relaxed models:"
EOF
    printf '"$QDM_ROOT/15-rosetta-modelling/extract/rosetta-scores.sh" -o scores -k total_score .\n'
    printf 'head -5 scores/scores-sorted.csv\n'
} > "$out/run.sh"
chmod +x "$out/run.sh"

if ((queue)); then
    info "job script ready: $out/run.sh"
    printf '\nSubmit it with:\n  bin/qdm-submit %s\n' "$out"
else
    info "running relax now (use -q to write the script and submit instead)"
    QDM_ROOT="$QDM_ROOT" "$out/run.sh"
fi
